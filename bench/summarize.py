"""Aggregate results/*.csv into results/summary.md (per model x test set means)."""
import csv
from collections import defaultdict
from statistics import mean

from painite_bench.config import RESULTS_DIR

COLS = [("psnr", "PSNR-Y ↑", 2), ("ssim", "SSIM ↑", 4), ("lpips", "LPIPS ↓", 4), ("dists", "DISTS ↓", 4),
        ("dE", "ΔE00 ↓", 2), ("halo", "Halo ↓", 3), ("detail", "Detail (1=ideal)", 2)]
SEAM = [("seam_psnr", "Tiled vs whole PSNR ↑", 1), ("seam_max", "Max diff (8-bit)", 1),
        ("seam_ratio", "Seam/interior diff", 2)]


def table(rows, cols, key):
    out = ["| Model | " + " | ".join(c[1] for c in cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for k, rs in rows.items():
        vals = []
        for c, _, nd in cols:
            v = [float(r[c]) for r in rs if r.get(c) not in (None, "")]
            vals.append(f"{mean(v):.{nd}f}" if v else "")
        out.append(f"| {key(k)} | " + " | ".join(vals) + " |")
    return "\n".join(out)


def main():
    md = ["# Bake-off results (generated by summarize.py)", ""]
    for op in ("denoise", "sharpen", "upscale2x"):
        p = RESULTS_DIR / f"quality_{op}.csv"
        if not p.exists():
            continue
        rows = list(csv.DictReader(open(p)))
        md += [f"## {op}", ""]
        by_set = defaultdict(lambda: defaultdict(list))
        for r in rows:
            by_set[r["set"]][r["model"]].append(r)
        for s, models in by_set.items():
            n = len(next(iter(models.values())))
            md += [f"### {s} ({n} images)", "", table(models, COLS, lambda k: k), ""]
        seam = defaultdict(list)
        for r in rows:
            if r.get("seam_psnr"):
                seam[r["model"]].append(r)
        if seam:
            md += ["### Tiling consistency (512 px tiles, 32 px overlap, vs one pass on a 1024 px crop)", "",
                   table(seam, SEAM, lambda k: k), ""]
    p = RESULTS_DIR / "latency.csv"
    if p.exists():
        rows = list(csv.DictReader(open(p)))
        md += ["## Latency and memory on spark1 (GB10)", "",
               "| Model | dtype | Batch | Load s | Preview p50 s | Preview p95 s | 12 MP s | 24 MP s | 48 MP s | Peak GB @48 MP |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        by = defaultdict(dict)
        for r in rows:
            by[(r["model"], r["dtype"])][int(r["mp"])] = r
        for (m, dt), d in by.items():
            f = next(iter(d.values()))
            cell = lambda mp: (d[mp]["full_s"] + ("*" if d[mp]["measured"] != "yes" else "")) if mp in d else ""
            peak = d.get(48, {}).get("peak_gb", "")
            md.append(f"| {m} | {dt} | {f['batch']} | {f['load_s']} | {f['preview_p50']} | {f['preview_p95']} | "
                      f"{cell(12)} | {cell(24)} | {cell(48)} | {peak} |")
        md += ["", "\\* extrapolated from per-tile throughput (projected over the 15-minute run budget).", ""]
    (RESULTS_DIR / "summary.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
