"""Tables for FACE_BAKEOFF.md from results/face/*.csv -> results/face/summary.md.

  python face/summarize.py
"""
import collections
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from painite_bench.config import RESULTS_DIR  # noqa: E402

R = RESULTS_DIR / "face"


def load(name):
    p = R / name
    return list(csv.DictReader(open(p))) if p.exists() else []


def mean(rows, k):
    return float(np.mean([float(r[k]) for r in rows])) if rows else float("nan")


def main():
    out = ["# Face bake-off: summary tables", "", "Generated by `face/summarize.py` from `results/face/*.csv`.", ""]

    syn = load("quality_synthetic.csv")
    g = collections.defaultdict(list)
    for r in syn:
        g[(r["model"], r["level"])].append(r)
    models = list(dict.fromkeys(r["model"] for r in syn))
    out += ["## Synthetic (100 CelebA-HQ faces, 512 px, ground truth)", "",
            "| Model | Mild PSNR | Mild LPIPS | Mild DISTS | Mild identity | Heavy PSNR | Heavy LPIPS | Heavy DISTS | Heavy identity | MUSIQ (mild) | s/face |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in models:
        a, b = g[(m, "mild")], g[(m, "heavy")]
        out.append(f"| {m} | {mean(a, 'psnr'):.2f} | {mean(a, 'lpips'):.3f} | {mean(a, 'dists'):.3f} | {mean(a, 'identity'):.3f} | "
                   f"{mean(b, 'psnr'):.2f} | {mean(b, 'lpips'):.3f} | {mean(b, 'dists'):.3f} | {mean(b, 'identity'):.3f} | "
                   f"{mean(a, 'musiq'):.1f} | {mean(a + b, 'sec'):.3f} |")

    st = load("strength_synthetic.csv")
    if st:
        out += ["", "## Strength (synthetic): out = input + s × (restored − input)", "",
                "| Model | Level | s | PSNR | LPIPS | DISTS | identity |", "|---|---|---|---|---|---|---|"]
        g = collections.defaultdict(list)
        for r in st:
            g[(r["model"], r["level"], r["strength"])].append(r)
        for (m, lv, s), rs in g.items():
            out.append(f"| {m} | {lv} | {s} | {mean(rs, 'psnr'):.2f} | {mean(rs, 'lpips'):.3f} | {mean(rs, 'dists'):.3f} | {mean(rs, 'identity'):.3f} |")

    real = load("quality_real.csv")
    if real:
        bins = [(0, 128), (128, 256), (256, 768), (768, 1e9)]
        out += ["", "## Real photos (19 Commons photos, 127 faces, full pipeline)", "",
                "Identity is ArcFace cosine to the same face in the input (1 = unchanged). Face size is the aligned crop side in source px.",
                "", "| Model | MUSIQ | CLIP-IQA | identity | " + " | ".join(f"id, size {a}–{b if b < 1e9 else '∞'} (n)" for a, b in bins) + " |",
                "|---|---|---|---|" + "---|" * len(bins)]
        g = collections.defaultdict(list)
        for r in real:
            g[r["model"]].append(r)
        for m, rs in g.items():
            cells = []
            for a, b in bins:
                sel = [r for r in rs if a <= float(r["size"]) < b]
                cells.append(f"{mean(sel, 'identity'):.3f} ({len(sel)})")
            out.append(f"| {m} | {mean(rs, 'musiq'):.1f} | {mean(rs, 'clipiqa'):.3f} | {mean(rs, 'identity'):.3f} | " + " | ".join(cells) + " |")

    lf = load("quality_largeface.csv")
    if lf:
        out += ["", "## Large faces (CelebA-HQ at face size L; restorer resamples to its own size and back)", "",
                "| L | Input | Policy | PSNR | LPIPS | DISTS | detail | identity |", "|---|---|---|---|---|---|---|---|"]
        g = collections.defaultdict(list)
        for r in lf:
            g[(r["size"], r["input"], r["policy"])].append(r)
        for (L, k, p), rs in g.items():
            out.append(f"| {L} | {k} | {p} | {mean(rs, 'psnr'):.2f} | {mean(rs, 'lpips'):.3f} | {mean(rs, 'dists'):.3f} | "
                       f"{mean(rs, 'detail'):.2f} | {mean(rs, 'identity'):.3f} |")

    lat = load("latency.csv")
    if lat:
        out += ["", "## Latency (spark1, GB10)", "", "| What | Model | dtype | Faces | Seconds | Peak GB |", "|---|---|---|---|---|---|"]
        for r in lat:
            pk = f"{float(r['peak_gb']):.1f}" if r["peak_gb"] else ""
            out.append(f"| {r['what']} | {r['model']} | {r['dtype']} | {r['faces']} | {float(r['sec']):.3f} | {pk} |")

    (R / "summary.md").write_text("\n".join(out) + "\n")
    print(R / "summary.md")


if __name__ == "__main__":
    main()
