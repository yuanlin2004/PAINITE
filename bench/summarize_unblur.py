"""Per-set tables for the unblur bake-off from results/quality_unblur*.csv -> results/unblur_summary.md

  python summarize_unblur.py [--csv quality_unblur.csv quality_unblur_hypir.csv ...]

Every table compares models on the same images (a model's mean is over the images it has;
the n column shows how many). Context-study rows are tagged @t<tile> / @whole.
"""
import argparse
import csv
from collections import defaultdict

import numpy as np

from painite_bench.config import RESULTS_DIR

METRICS = ["psnr", "ssim", "lpips", "dists", "halo", "detail", "seconds"]
LOWER = {"lpips", "dists", "halo", "seconds"}


def load(files):
    rows = []
    for f in files:
        p = RESULTS_DIR / f
        if p.exists():
            with open(p) as fh:
                rows += list(csv.DictReader(fh))
    return rows


def table(rows, sub, only=None):
    by = defaultdict(list)
    for r in rows:
        if r["set"] == sub and (only is None or r["model"] in only):
            by[r["model"]].append(r)
    if not by:
        return ""
    # means over the images the fully-run models share; partially-run models (fewer images,
    # e.g. the slow ones in the screening) are averaged over what they have, see n
    nmax = max(len(rs) for rs in by.values())
    common = set.intersection(*[{r["image"] for r in rs} for rs in by.values() if len(rs) == nmax])
    stats = {}
    for m, rs in by.items():
        rs = [r for r in rs if r["image"] in common] or rs
        stats[m] = {k: np.mean([float(r[k]) for r in rs if r.get(k) not in ("", None)] or [np.nan]) for k in METRICS}
        stats[m]["n"] = len(rs)
    order = sorted(stats, key=lambda m: (m != "input", -stats[m]["psnr"] if sub.endswith("sharp") else stats[m]["lpips"]))
    best = {k: (min if k in LOWER else max)(s[k] for m, s in stats.items() if m != "input") for k in METRICS}
    out = [f"### {sub} ({len(common)} images)\n", "| model | " + " | ".join(METRICS) + " | n |",
           "|---" * (len(METRICS) + 2) + "|"]
    for m in order:
        cells = []
        for k in METRICS:
            v = stats[m][k]
            s = "" if np.isnan(v) else f"{v:.4f}" if k in ("ssim", "lpips", "dists") else f"{v:.2f}"
            cells.append(f"**{s}**" if m != "input" and v == best[k] and k != "detail" else s)
        out.append(f"| {m.removeprefix('unblur/')} | " + " | ".join(cells) + f" | {stats[m]['n']} |")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", nargs="*", default=["quality_unblur.csv", "quality_unblur_hypir.csv"])
    ap.add_argument("--out", default="unblur_summary.md")
    a = ap.parse_args()
    rows = load(a.csv)
    sets = list(dict.fromkeys(r["set"] for r in rows))
    md = ["# Unblur bake-off: per-set tables\n",
          f"Generated by summarize_unblur.py from {', '.join(a.csv)}. Sorted by LPIPS "
          "(PSNR for the sharp set); best per column in bold. n < the set's image count means the "
          "model was only run on the first n images (slow models in the screening).\n"]
    md += [table(rows, s) for s in sets]
    (RESULTS_DIR / a.out).write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
